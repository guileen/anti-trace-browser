import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
const root=resolve(import.meta.dirname,'../..');
const upstream=resolve(process.argv[2]||resolve(root,'../../obscura-upstream'));
const source=resolve(root,'.local/obscura-cost/source');
const commit='7c751c5cd8833ac951d48320218c4fe91aa97ac8';
const patch=resolve(import.meta.dirname,'runtime-environment.patch');
const run=(args,cwd=upstream)=>{const p=spawnSync('git',args,{cwd,encoding:'utf8'});if(p.status!==0)throw new Error(p.stderr||p.stdout);return p.stdout;};
const metadata=JSON.parse(readFileSync(resolve(import.meta.dirname,'native-schema3-preparation.json'),'utf8'));
if(createHash('sha256').update(readFileSync(patch)).digest('hex')!==metadata.patch.sha256)throw new Error('Patch digest mismatch');
if(existsSync(source))throw new Error('Source already exists; do not overwrite a worktree. Use existing prepared source or choose a fresh checkout.');
mkdirSync(resolve(root,'.local/obscura-cost'),{recursive:true});
run(['cat-file','-e',commit+'^{commit}']);
run(['worktree','add','--detach',source,commit]);
run(['apply','--check',patch],source);
run(['apply',patch],source);
console.log(JSON.stringify({source,commit,patch,build:'node candidates/obscura/build.mjs',smoke:'node candidates/obscura/smoke.mjs'},null,2));
